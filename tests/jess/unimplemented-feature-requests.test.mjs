test('Android app usage reporting requires owner-granted Usage Access and is exposed through the phone command bridge', async () => {
  const reader = await read('../../android/app/src/main/java/com/example/hubmind/agent/AndroidUsageStatsReader.kt');
  const executor = await read('../../android/app/src/main/java/com/example/hubmind/agent/AndroidUiActionExecutor.kt');
  const manifest = await read('../../android/app/src/main/AndroidManifest.xml');
  const model = await read('../../android/app/src/main/java/com/example/hubmind/agent/AgentModels.kt');
  const bridge = await read('../../android/app/src/main/java/com/example/hubmind/data/transport/ControlPlaneTransport.kt');
  const tools = await read('../../src/lib/jessTools.ts');

  assert.match(reader, /OPSTR_GET_USAGE_STATS/);
  assert.match(reader, /queryUsageStats/);
  assert.match(reader, /hasUsageAccess/);
  assert.match(reader, /owner must explicitly grant/i);
  assert.match(manifest, /PACKAGE_USAGE_STATS/);
  assert.match(model, /GET_APP_USAGE_STATS/);
  assert.match(model, /OPEN_USAGE_ACCESS_SETTINGS/);
  assert.match(executor, /AndroidUsageStatsReader/);
  assert.match(executor, /ACTION_USAGE_ACCESS_SETTINGS/);
  assert.match(bridge, /GET_APP_USAGE_STATS/);
  assert.match(tools, /GET_APP_USAGE_STATS/);
  assert.match(tools, /OPEN_USAGE_ACCESS_SETTINGS/);
});

