import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const read = (path) => readFile(new URL(path, import.meta.url), 'utf8');

test('Jess has grounded local time, predictive tasking, pair-programmer and project documentation tools', async () => {
  const tools = await read('../../src/lib/jessTools.ts');
  const live = await read('../../src/services/liveAudioClient.ts');

  for (const name of ['get_local_time_context', 'get_predictive_tasking', 'get_code_review_context', 'generate_project_documentation']) {
    assert.match(tools, new RegExp(`name: '${name}'`));
    assert.match(tools, new RegExp(`case '${name}'`));
  }

  assert.match(tools, /Intl\.DateTimeFormat\(\)\.resolvedOptions\(\)\.timeZone/);
  assert.match(tools, /overdue/);
  assert.match(tools, /advisoryOnly: true/);
  assert.match(tools, /sourceCode: numbered/);
  assert.match(tools, /Source Access Warnings/);
  assert.match(tools, /isAutoGeneratedProjectDoc/);
  assert.match(tools, /createNamedCheckpoint/);
  assert.match(live, /DEVICE LOCAL TIME & TIME ZONES/);
  assert.match(live, /PREDICTIVE TASKING/);
  assert.match(live, /AI PAIR PROGRAMMER/);
  assert.match(live, /PROJECT DOCUMENTATION/);
});

test('Project-linked task creation and updates refresh generated project documentation', async () => {
  const tools = await read('../../src/lib/jessTools.ts');
  const createStart = tools.indexOf("case 'create_task'");
  const updateStart = tools.indexOf("case 'update_task'");
  const deleteStart = tools.indexOf("case 'delete_task'");
  const create = tools.slice(createStart, updateStart);
  const update = tools.slice(updateStart, deleteStart);

  assert.match(create, /projectId: args\.projectId \|\| null/);
  assert.match(create, /generate_project_documentation/);
  assert.match(update, /'projectId'/);
  assert.match(update, /generate_project_documentation/);
});

